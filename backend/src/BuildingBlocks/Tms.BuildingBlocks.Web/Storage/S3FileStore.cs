using System.Net;
using Amazon.S3;
using Amazon.S3.Model;
using Microsoft.Extensions.Options;
using Tms.SharedKernel.Contracts;

namespace Tms.BuildingBlocks.Web.Storage;

/// <summary>Stores blobs as objects in an S3 bucket. Keys stay exactly as the application generated them; <see cref="S3StorageOptions.KeyPrefix"/> is added here only.</summary>
public sealed class S3FileStore : IFileStore
{
    private readonly IAmazonS3 _s3;
    private readonly string _bucket;
    private readonly string _prefix;

    public S3FileStore(IAmazonS3 s3, IOptions<StorageOptions> options)
    {
        _s3 = s3;
        _bucket = options.Value.S3.BucketName;
        var prefix = (options.Value.S3.KeyPrefix ?? "").Trim().Trim('/');
        _prefix = prefix.Length == 0 ? "" : prefix + "/";
    }

    public async Task SaveAsync(string key, Stream content, CancellationToken cancellationToken = default)
    {
        var request = new PutObjectRequest
        {
            BucketName = _bucket,
            Key = ObjectKey(key),
            ServerSideEncryptionMethod = ServerSideEncryptionMethod.AES256,
        };

        // S3 needs the length up front; callers hand over seekable streams, but never assume it.
        if (content.CanSeek)
        {
            request.InputStream = content;
            await _s3.PutObjectAsync(request, cancellationToken);
            return;
        }

        await using var buffer = new MemoryStream();
        await content.CopyToAsync(buffer, cancellationToken);
        buffer.Position = 0;
        request.InputStream = buffer;
        await _s3.PutObjectAsync(request, cancellationToken);
    }

    public async Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken = default)
    {
        try
        {
            var response = await _s3.GetObjectAsync(_bucket, ObjectKey(key), cancellationToken);
            return new ResponseStream(response);
        }
        catch (AmazonS3Exception ex) when (ex.StatusCode == HttpStatusCode.NotFound)
        {
            return null;
        }
    }

    public async Task DeleteAsync(string key, CancellationToken cancellationToken = default) =>
        await _s3.DeleteObjectAsync(_bucket, ObjectKey(key), cancellationToken);

    /// <summary>Keys are generated by the application; this still refuses anything that could address another place.</summary>
    private string ObjectKey(string key)
    {
        if (string.IsNullOrWhiteSpace(key) || key.StartsWith('/') || key.Contains('\\') || key.Split('/').Any(part => part is ".." or "." or ""))
        {
            throw new ArgumentException("Invalid storage key.", nameof(key));
        }

        return _prefix + key;
    }

    /// <summary>Hands out the object's stream and disposes the whole response with it.</summary>
    private sealed class ResponseStream(GetObjectResponse response) : Stream
    {
        private readonly Stream _inner = response.ResponseStream;

        public override bool CanRead => true;
        public override bool CanSeek => false;
        public override bool CanWrite => false;
        public override long Length => response.ContentLength;
        public override long Position { get => throw new NotSupportedException(); set => throw new NotSupportedException(); }
        public override void Flush() { }
        public override int Read(byte[] buffer, int offset, int count) => _inner.Read(buffer, offset, count);
        public override ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default) => _inner.ReadAsync(buffer, cancellationToken);
        public override Task<int> ReadAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken) => _inner.ReadAsync(buffer, offset, count, cancellationToken);
        public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
        public override void SetLength(long value) => throw new NotSupportedException();
        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();

        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                response.Dispose();
            }

            base.Dispose(disposing);
        }
    }
}
